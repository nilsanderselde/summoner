/// Returns all curated factory presets.
pub fn all_factory_presets() -> &'static [FactoryPreset] {
    FACTORY_PRESETS
}

/// Finds a factory preset by case-insensitive name or ID.
pub fn find_preset(name_or_id: &str) -> Option<&'static FactoryPreset> {
    let query = name_or_id.trim().to_lowercase();
    FACTORY_PRESETS.iter().find(|p| {
        p.id.eq_ignore_ascii_case(&query)
            || p.name.eq_ignore_ascii_case(&query)
            || query.contains(&p.id.to_lowercase())
            || query.contains(&p.name.to_lowercase())
    })
}

/// Returns presets belonging to a specific category.
pub fn presets_by_category(cat: FactoryPresetCategory) -> Vec<&'static FactoryPreset> {
    FACTORY_PRESETS.iter().filter(|p| p.category == cat).collect()
}

/// Returns all demo project templates.
pub fn all_demo_templates() -> &'static [FactoryDemoTemplate] {
    FACTORY_DEMO_TEMPLATES
}

/// Finds a demo project template by case-insensitive ID or title.
pub fn find_demo_template(id_or_title: &str) -> Option<&'static FactoryDemoTemplate> {
    let query = id_or_title.trim().to_lowercase();
    FACTORY_DEMO_TEMPLATES.iter().find(|t| {
        t.id.eq_ignore_ascii_case(&query)
            || t.title.eq_ignore_ascii_case(&query)
            || query.contains(&t.id.to_lowercase())
            || query.contains(&t.title.to_lowercase())
    })
}
