//! Production-Grade Factory Preset & Soundbank Engine.
//! Provides curated out-of-the-box presets spanning Physical Modeling, General MIDI,
//! Chiptune/Tracker, Microtonal Harmony, Modern Synths, Studio FX, and Demo Song Templates.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum FactoryPresetCategory {
    PhysicalModeling,
    GeneralMidi,
    ChiptuneTracker,
    MicrotonalHarmony,
    ModernSynth,
    StudioFx,
    DrumsPercussion,
}

impl FactoryPresetCategory {
    pub fn name(&self) -> &'static str {
        match self {
            Self::PhysicalModeling => "Physical Modeling",
            Self::GeneralMidi => "General MIDI",
            Self::ChiptuneTracker => "Chiptune & Tracker",
            Self::MicrotonalHarmony => "Microtonal & Harmony",
            Self::ModernSynth => "Modern Synth & Lo-Fi",
            Self::StudioFx => "Studio FX & Mastering",
            Self::DrumsPercussion => "Drums & Percussion",
        }
    }

    pub fn icon(&self) -> &'static str {
        match self {
            Self::PhysicalModeling => "🎻",
            Self::GeneralMidi => "🎹",
            Self::ChiptuneTracker => "👾",
            Self::MicrotonalHarmony => "✨",
            Self::ModernSynth => "⚡",
            Self::StudioFx => "🎛",
            Self::DrumsPercussion => "🥁",
        }
    }

    pub fn color_rgb(&self) -> (u8, u8, u8) {
        match self {
            Self::PhysicalModeling => (234, 179, 8),    // Amber / Gold
            Self::GeneralMidi => (56, 189, 248),        // Sky Blue
            Self::ChiptuneTracker => (239, 68, 68),     // Bright Red
            Self::MicrotonalHarmony => (168, 85, 247),  // Purple / Violet
            Self::ModernSynth => (236, 72, 153),        // Pink / Magenta
            Self::StudioFx => (16, 185, 129),           // Emerald Green
            Self::DrumsPercussion => (249, 115, 22),    // Orange
        }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct FactoryPreset {
    pub id: &'static str,
    pub name: &'static str,
    pub category: FactoryPresetCategory,
    pub target_node_kind: &'static str,
    pub description: &'static str,
    pub tags: &'static [&'static str],
    pub macro_tone: f32,
    pub macro_space: f32,
    pub macro_punch: f32,
    pub macro_character: f32,
    pub params: &'static [(&'static str, f32)],
    pub tuning_edo: Option<u16>,
    pub sample_preview_note: u8,
}

#[derive(Debug, Clone, Serialize)]
pub struct DemoTrackData {
    pub id: usize,
    pub name: &'static str,
    pub color_rgb: [u8; 3],
    pub is_audio: bool,
    pub gain: f32,
    pub pan: f32,
    pub preset_id: &'static str,
    pub clip_start_beat: f64,
    pub clip_length_beats: f64,
    pub notes: &'static [(u8, f64, f64, f32)], // (pitch_idx, start_beat, length_beats, velocity)
}

#[derive(Debug, Clone, Serialize)]
pub struct FactoryDemoTemplate {
    pub id: &'static str,
    pub title: &'static str,
    pub description: &'static str,
    pub bpm: f64,
    pub key_signature: &'static str,
    pub time_signature: &'static str,
    pub tuning_name: &'static str,
    pub tuning_edo: Option<u16>,
    pub tracks: &'static [DemoTrackData],
}

